package Core_java;

public class Static_final { 
	 
	 static int value=90;
	 final int num=100;
//	 using the final keyword the value cannot be changed and cannot be inherited  
//	 static can be called without using the object

	 public static void main(String[] args) {
		  Static_final s=new Static_final();
		  System.out.println(value);
	        System.out.println(s.num);
		  
	 }	  
	  
 }

